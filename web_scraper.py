import requests
from bs4 import BeautifulSoup
import pandas as pd

url = "https://books.toscrape.com/"

response = requests.get(url, timeout=20)

print("Status code:", response.status_code)
print(response.text[:500])

soup = BeautifulSoup(response.text, "html.parser")

books = soup.select("article.product_pod")

print("Books found:", len(books))

first_book = books[0]

title = first_book.h3.a["title"]
price = first_book.select_one(".price_color").get_text(strip=True)
availability = first_book.select_one(".availability").get_text(strip=True)
rating = first_book.select_one(".star-rating")["class"][1]

print("Book Title:", title)
print("Price:", price)
print("Rating:", rating)
print("Availability:", availability)

data = []

for book in books:
    title = book.h3.a["title"]
    price = book.select_one(".price_color").get_text(strip=True)
    rating = book.select_one(".star-rating")["class"][1]
    availability = book.select_one(".availability").get_text(strip=True)
    link = book.h3.a["href"]

    data.append({
        "Title": title,
        "Price": price,
        "Rating": rating,
        "Availability": availability,
        "Book_URL": link
    })

print("Total books collected:", len(data))
print(data[:2])

df = pd.DataFrame(data)

display(df.head())

print("Rows and columns:", df.shape)

from urllib.parse import urljoin

base_url = "https://books.toscrape.com/"
next_url = base_url
all_data = []

while next_url:
    response = requests.get(next_url, timeout=20)
    response.raise_for_status()

    soup = BeautifulSoup(response.text, "html.parser")

    books = soup.select("article.product_pod")

    for book in books:
        title = book.h3.a["title"]
        price = book.select_one(".price_color").get_text(strip=True)
        rating = book.select_one(".star-rating")["class"][1]
        availability = " ".join(
            book.select_one(".availability").get_text(strip=True).split()
        )
        book_url = urljoin(next_url, book.h3.a["href"])

        all_data.append({
            "Title": title,
            "Price": price,
            "Rating": rating,
            "Availability": availability,
            "Book_URL": book_url
        })

    next_button = soup.select_one("li.next a")

    if next_button:
        next_url = urljoin(next_url, next_button["href"])
    else:
        next_url = None

    print("Total collected so far:", len(all_data))

print("Scraping completed!")
print("Total books collected:", len(all_data))

df = pd.DataFrame(all_data)

print("Dataset shape:", df.shape)

display(df.head(10))

# Remove currency symbols and other unwanted characters
df["Price"] = (
    df["Price"]
    .str.replace(r"[^0-9.]", "", regex=True)
    .astype(float)
)

print(df["Price"].head())
print("Price conversion successful!")

